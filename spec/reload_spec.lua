describe("package manager buffer reload", function()
	it("refreshes the original buffer from a regular callback", function()
		local path = vim.fn.tempname()
		vim.fn.writefile({ "before" }, path)
		vim.cmd.edit(path)
		local buf = vim.api.nvim_get_current_buf()
		vim.fn.writefile({ "after removal, different length" }, path)
		vim.cmd.enew()
		require("npackages.ui.reload")(buf)
		assert.is_true(vim.wait(1000, function()
			return vim.api.nvim_buf_get_lines(buf, 0, 1, false)[1] == "after removal, different length"
		end))
		vim.api.nvim_buf_delete(buf, { force = true })
		vim.fn.delete(path)
	end)
end)
